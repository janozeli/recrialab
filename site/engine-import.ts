// Brings the fit engine's garments into the site. Usage (in site/): bun engine-import.ts WORK COMMIT [PATCH]
// WORK is the folder written by `python3 tools/fit/engine.py WORK` and COMMIT the commit of tools/fit it ran at
// (PATCH: the sha256 of a patch applied over it, when the run was ahead of the branch). Copies WORK/final/NNN-*.glb of every garment
// that is not on hold (engine-hold.ts) and the two low-poly bodies into assets/engine/, byte for byte, and writes
// engine-garments.ts (the imports) and engine.lock.json (the hash of each file and the engine commit they came from).
import { createHash } from 'node:crypto';
import { execSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { CATALOG } from './catalog-data';
import { ENGINE_HOLD } from './engine-hold';

const SITE = new URL('.', import.meta.url).pathname;
const OUT = join(SITE, 'assets', 'engine');
const work = resolve(process.argv[2] ?? '');
if (!process.argv[3] || !existsSync(join(work, 'final'))) throw new Error('usage: bun engine-import.ts WORK COMMIT (the folder written by tools/fit/engine.py and the commit it ran at)');

const sha = (path: string) => createHash('sha256').update(readFileSync(path)).digest('hex');
const finals = readdirSync(join(work, 'final')).filter(f => /^\d{3}-[a-z]+\.glb$/.test(f)).sort();
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const files: Record<string, string> = {};
const copy = (from: string, name: string) => { copyFileSync(from, join(OUT, name)); files[name] = sha(join(OUT, name)); };
copy(join(work, 'low-B.glb'), 'body-b.glb');
copy(join(work, 'low-C.glb'), 'body-c.glb');
const parts: Record<string, string[]> = {};
for (const { id } of CATALOG) {
  if (id in ENGINE_HOLD) continue;
  parts[id] = finals.filter(f => f.startsWith(`${id}-`));
  if (!parts[id].length) throw new Error(`${id}: no part in ${work}/final and not on hold in engine-hold.ts`);
  for (const f of parts[id]) copy(join(work, 'final', f), f);
}

const name = (f: string) => 'g' + f.replace('.glb', '').replace('-', '_');
const all = Object.values(parts).flat();
writeFileSync(join(SITE, 'engine-garments.ts'), `// Written by engine-import.ts: the garments rebuilt by the fit engine (tools/fit/engine.py) and their low-poly bodies.
// To put a garment back as published, add it to engine-hold.ts; do not edit this file by hand.
import bodyB from './assets/engine/body-b.glb';
import bodyC from './assets/engine/body-c.glb';
${all.map(f => `import ${name(f)} from './assets/engine/${f}';`).join('\n')}

export const ENGINE_BODY_URLS = { B: bodyB, C: bodyC } as const;
/** The parts of each garment: the shell on the body and, where the garment has them, the welded tube and the loose hood. */
export const ENGINE_PARTS: Record<string, readonly string[]> = {
${Object.entries(parts).map(([id, fs]) => `  '${id}': [${fs.map(name).join(', ')}],`).join('\n')}
};
`);
// A 40-character commit is taken as given (it may not be fetched here); a short one is resolved in this repository.
const commit = /^[0-9a-f]{40}$/.test(process.argv[3]) ? process.argv[3] : execSync(`git rev-parse ${process.argv[3]}`, { cwd: SITE, encoding: 'utf8' }).trim();
const patch = process.argv[4];
if (patch && !/^[0-9a-f]{64}$/.test(patch)) throw new Error('PATCH is the sha256 of the patch applied over COMMIT');
writeFileSync(join(SITE, 'engine.lock.json'), JSON.stringify({ engine: commit, ...(patch ? { patch } : {}), files }, null, 1) + '\n');
console.log(`${Object.keys(parts).length} garments from the engine (${all.length} parts), ${Object.keys(ENGINE_HOLD).length} on hold as published`);
